import type { AdminDashboardSummary, AdminTask } from '@/types/admin';
import { buildDashboardSummary } from '@/lib/admin/analytics';

export interface ReportFilterOptions {
  scope: 'all' | 'receivables' | 'completed' | 'active';
  fromDate?: string;
  toDate?: string;
}

export function formatCurrencyINR(amount: number): string {
  return new Intl.NumberFormat('en-IN', {
    style: 'currency',
    currency: 'INR',
    maximumFractionDigits: 0,
  }).format(amount);
}

export function filterTasksForReport(
  tasks: AdminTask[],
  options: ReportFilterOptions
): AdminTask[] {
  return tasks.filter((task) => {
    if (options.scope === 'receivables' && (task.amountToReceive <= 0 || task.status === 'cancelled')) {
      return false;
    }
    if (options.scope === 'completed' && task.status !== 'completed') {
      return false;
    }
    if (
      options.scope === 'active' &&
      task.status !== 'pending' &&
      task.status !== 'in_progress' &&
      task.status !== 'review'
    ) {
      return false;
    }
    if (options.fromDate && task.dueDate < options.fromDate) {
      return false;
    }
    if (options.toDate && task.dueDate > options.toDate) {
      return false;
    }
    return true;
  });
}

function escapeCsvCell(value: string | number | null | undefined): string {
  const str = String(value ?? '');
  if (/[",\n\r]/.test(str)) {
    return `"${str.replace(/"/g, '""')}"`;
  }
  return str;
}

function escapeHtml(value: string | number | null | undefined): string {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

export function buildCsvReport(
  tasks: AdminTask[],
  generatedBy: string,
  options: ReportFilterOptions
): string {
  const summary: AdminDashboardSummary = buildDashboardSummary(tasks);
  const generatedAt = new Date().toISOString();

  const lines: string[] = [
    ['Motionxyne Admin Portal — Detailed Financial & Task Audit Report'].map(escapeCsvCell).join(','),
    ['Generated At', generatedAt].map(escapeCsvCell).join(','),
    ['Generated By', generatedBy].map(escapeCsvCell).join(','),
    ['Report Scope', options.scope].map(escapeCsvCell).join(','),
    ['Date Range', `${options.fromDate || 'All'} to ${options.toDate || 'All'}`].map(escapeCsvCell).join(','),
    '',
    ['EXECUTIVE SUMMARY'].map(escapeCsvCell).join(','),
    ['Total Tasks', summary.totalTasks].map(escapeCsvCell).join(','),
    ['Completed Tasks', summary.completedTasks].map(escapeCsvCell).join(','),
    ['Active Tasks', summary.activeTasks].map(escapeCsvCell).join(','),
    ['Total Billed (INR)', summary.totalBilled].map(escapeCsvCell).join(','),
    ['Amount Collected (INR)', summary.totalCollected].map(escapeCsvCell).join(','),
    ['Amount To Be Received (INR)', summary.totalToReceive].map(escapeCsvCell).join(','),
    ['Collection Rate (%)', `${summary.collectionRate}%`].map(escapeCsvCell).join(','),
    '',
    [
      'Task ID',
      'Title',
      'Client Name',
      'Client Email',
      'Service Type',
      'Assigned To',
      'Status',
      'Priority',
      'Due Date',
      'Total Amount (INR)',
      'Amount Collected (INR)',
      'Amount To Be Received (INR)',
      'Payment Status',
      'Notes',
    ]
      .map(escapeCsvCell)
      .join(','),
  ];

  for (const t of tasks) {
    lines.push(
      [
        t.id,
        t.title,
        t.clientName,
        t.clientEmail || '',
        t.serviceType,
        t.assignedTo,
        t.status,
        t.priority,
        t.dueDate,
        t.totalAmount,
        t.amountCollected,
        t.amountToReceive,
        t.paymentStatus,
        t.notes || '',
      ]
        .map(escapeCsvCell)
        .join(',')
    );
  }

  return lines.join('\r\n');
}

export function buildJsonReport(
  tasks: AdminTask[],
  generatedBy: string,
  options: ReportFilterOptions
): string {
  const summary = buildDashboardSummary(tasks);
  return JSON.stringify(
    {
      reportTitle: 'Motionxyne Detailed Task & Financial Audit Report',
      generatedAt: new Date().toISOString(),
      generatedBy,
      filters: options,
      summary,
      tasks,
    },
    null,
    2
  );
}

